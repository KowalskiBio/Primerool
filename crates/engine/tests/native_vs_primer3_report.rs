//! Documented (not hard-gated) comparison between `NativeBackend` and
//! `Primer3Backend` running through the exact same `engine::picker`
//! pipeline on a realistic template — the concrete demonstration that
//! `scan_candidates`/`score_candidates`/`rank` are genuinely
//! backend-agnostic, plus a real numeric comparison of the one metric
//! both backends compute meaningfully (Tm; see `backend_native.rs`'s
//! docs on why hairpin/dimer `tm` is `None` for the native backend).
//!
//! Not a parity gate: the two backends use different Tm models
//! (Primer3's salt-corrected nearest-neighbor thermodynamic alignment vs.
//! Strider's own NN + Owczarzy salt-correction formulas), so exact
//! agreement isn't the goal — "close enough to both be defensible primer
//! Tm estimates" is.

use std::fmt::Write as _;
use std::time::Instant;

